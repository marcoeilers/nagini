# Generates tests for the ways of leaving try, with and loop statements: one for
# every nesting of these statements up to a depth, with every way of leaving at
# the innermost point. Each block logs a digit into c.val. CPython runs each
# function, and what it observes becomes the postcondition, which must verify
# without an error. A twin with a wrong postcondition must fail there.
#
# The tests in functional/verification/exits are those of the default options.

import argparse
import itertools
import os
import re
import sys
import types
import warnings

HEADER = '''# Any copyright is dedicated to the Public Domain.
# http://creativecommons.org/publicdomain/zero/1.0/

# Generated by tests/generate_exit_tests.py.

from typing import Optional

from nagini_contracts.contracts import *


class Cell:
    def __init__(self) -> None:
        self.val = 0
        Ensures(Acc(self.val) and self.val == 0)


class E1(Exception):
    pass


class E2(Exception):
    pass


def throw1() -> None:
    Ensures(False)
    Exsures(E1, True)
    raise E1()


class Manager:
    def __init__(self, c: Cell, d: int) -> None:
        self.c = c
        self.d = d
        Ensures(Acc(self.c) and self.c is c and Acc(self.d) and self.d == d)

    def __enter__(self) -> 'Manager':
        return self

    def __exit__(self, t: object, e: object, tb: object) -> bool:
        Requires(Acc(self.c, 1/2) and Acc(self.d, 1/2) and Acc(self.c.val))
        Ensures(Acc(self.c, 1/2) and Acc(self.d, 1/2) and Acc(self.c.val))
        Ensures(self.c.val == Old(self.c.val) * 10 + (self.d if e is None else 9))
        self.c.val = self.c.val * 10 + (self.d if e is None else 9)
        return e is None
'''

WRONG = '#:: ExpectedOutput(postcondition.violated:assertion.false)'

# The innermost statement. GUARD is true when it is reached: always, or in the
# second pass of the innermost twice-run loop around it.
EXITS = {
    'pass': ['pass'],
    'ret': ['if GUARD:', '    return 7'],
    'call': ['throw1()'],
    'raise': ['if GUARD:', '    raise E2()'],
    'brk': ['if GUARD:', '    break'],
    'cont': ['if GUARD:', '    continue'],
}


def log(d):
    return f'c.val = c.val * 10 + {d}'


def ind(lines):
    return ['    ' + line for line in lines]


# Frames: each wraps the inner lines and takes its digits from d.

def f_try_finally(inner, d):
    return ['try:'] + ind(inner) + ['finally:'] + ind([log(next(d))])


def f_try_except(inner, d):
    return ['try:'] + ind(inner) + ['except E1:'] + ind([log(next(d))])


def f_try_except_finally(inner, d):
    return (['try:'] + ind(inner) + ['except E2:'] + ind([log(next(d))]) +
            ['finally:'] + ind([log(next(d))]))


def f_handler(inner, d):
    return (['try:', '    throw1()', 'except E1:'] + ind(inner) +
            ['finally:'] + ind([log(next(d))]))


def f_else(inner, d):
    return (['try:'] + ind([log(next(d))]) + ['except E1:', '    pass', 'else:'] +
            ind(inner) + ['finally:'] + ind([log(next(d))]))


def f_finally(inner, d):
    return ['try:'] + ind([log(next(d))]) + ['finally:'] + ind(inner)


def f_finally_raising(inner, d):
    return ['try:', '    throw1()', 'except E2:', '    pass', 'finally:'] + ind(inner)


def f_finally_returning(inner, d):
    return ['try:', '    if b:', '        return 3', 'finally:'] + ind(inner)


def f_try_finally_break(inner, d):
    return ['try:'] + ind(inner) + ['finally:', '    if GUARD:', '        break']


def f_with(inner, d):
    a = next(d)
    return [f'm{a} = Manager(c, {a})', f'with m{a}:'] + ind(inner)


def f_loop(inner, d):
    a, e = next(d), next(d)
    return ([f'go{a} = True', f'while go{a}:', f'    INVARIANT go{a}', f'    go{a} = False'] +
            ind(inner) + ['else:', f'    LOOPEXIT go{a}', '    ' + log(e), log(a)])


def f_loop_twice(inner, d):
    a, e = next(d), next(d)
    inner = [line.replace('GUARD', f'i{a} == 2') for line in inner]
    return ([f'i{a} = 0', f'while i{a} < 2:', f'    INVARIANT i{a}', f'    i{a} = i{a} + 1'] +
            ind(inner) + ['else:', f'    LOOPEXIT i{a}', '    ' + log(e), log(a)])


def f_for_twice(inner, d):
    a, e = next(d), next(d)
    inner = [line.replace('GUARD', f'n{a} == 2') for line in inner]
    return ([f'n{a} = 0', f'for k_n{a} in range(0, 2):', f'    INVARIANT n{a} k_n{a}',
             f'    n{a} = n{a} + 1'] +
            ind(inner) + ['else:', f'    LOOPEXIT n{a}', '    ' + log(e), log(a)])


FRAMES = {'tf': f_try_finally, 'te': f_try_except, 'tef': f_try_except_finally,
          'h': f_handler, 'el': f_else, 'fin': f_finally, 'finx': f_finally_raising,
          'finr': f_finally_returning, 'tfbrk': f_try_finally_break, 'w': f_with,
          'loop': f_loop, 'loop2': f_loop_twice, 'for': f_for_twice}
FINALLY_FRAMES = ('fin', 'finx', 'finr')
LOOP_FRAMES = ('loop', 'loop2', 'for')
MODES = ('plain', 'inline', 'inherit')


def valid(frames, exit):
    """Whether the nesting (outermost first) is legal Python that Nagini accepts."""
    for i, frame in enumerate(frames):
        if frame == 'tfbrk' and not any(f in LOOP_FRAMES for f in frames[:i]):
            return False
    if exit in ('brk', 'cont'):
        loops = [i for i, f in enumerate(frames) if f in LOOP_FRAMES]
        if not loops:
            return False
        # Nagini rejects continue in a finally block.
        if exit == 'cont' and any(f in FINALLY_FRAMES for f in frames[loops[-1] + 1:]):
            return False
    return True


def build(frames, exit):
    digits = iter(range(1, 9))
    lines = EXITS[exit] + [log(next(digits))]
    for frame in reversed(frames):
        lines = FRAMES[frame](lines, digits)
    # The function ends without a return statement.
    return [line.replace('GUARD', 'b') for line in lines]


def enclosing(lines, index, pattern):
    """The matches of pattern in the headers of the blocks around a line, outermost first."""
    result = []
    depth = len(lines[index]) - len(lines[index].lstrip())
    for line in reversed(lines[:index]):
        d = len(line) - len(line.lstrip())
        if d < depth:
            depth = d
            match = re.match(pattern, line.strip())
            if match:
                result.append(match.group(1))
    return result[::-1]


def control_vars(lines, index):
    """The variables that count the passes of the loops around a line."""
    word = lines[index].strip().split(' ')
    names = enclosing(lines, index, r'(?:while |for k_)(\w+)')
    # The else block of a loop is not inside it.
    return names + [word[1]] if word[0] == 'LOOPEXIT' else names


def state(name, value):
    if isinstance(value, bool):
        return name if value else f'not {name}'
    return f'{name} == {value}'


def render(name, lines, contract, loop_states, mode):
    """loop_states None: the instrumented version that CPython runs."""
    out = []
    for i, line in enumerate(lines):
        pad = line[:len(line) - len(line.lstrip())]
        word = line.strip().split(' ')
        if word[0] in ('INVARIANT', 'LOOPEXIT'):
            names = control_vars(lines, i)
            if loop_states is None:
                out.append(f'{pad}LOG("{word[1]}", ({", ".join(names)},), c.val)')
            elif word[0] == 'INVARIANT':
                perms = ''.join(f' and Acc(m{k}.c) and m{k}.c is c and Acc(m{k}.d) and m{k}.d == {k}'
                                for k in enclosing(lines, i, r'with m(\d+)'))
                out.append(f'{pad}Invariant(Acc(c.val){perms})')
                if len(word) > 2:
                    out.append(f'{pad}Invariant({word[1]} == len(Previous({word[2]})))')
                # The states in which CPython reaches the loop condition.
                options = [' and '.join([state(n, v) for n, v in zip(names, values)] +
                                        [f'c.val == {val}'])
                           for values, val in loop_states[word[1]].items()]
                out.append(f'{pad}Invariant({" or ".join("(" + o + ")" for o in options)})')
        else:
            out.append(line)
    return assemble(name, contract, out, mode)


def assemble(name, contract, body, mode):
    """
    plain: the nesting is the function. inline: it is an inlined function,
    called in a try block whose finally logs 8. inherit: it is a method of A,
    which B inherits.
    """
    requires = ['Requires(Acc(c.val) and c.val == 0 and b)']
    if mode == 'inline':
        return '\n'.join(
            ['@Inline', f'def g_{name}(c: Cell, b: bool) -> Optional[int]:'] + ind(body) +
            ['', '', f'def {name}(c: Cell, b: bool) -> Optional[int]:'] +
            ind(requires + contract) +
            ['    try:', f'        r = g_{name}(c, b)', '    finally:', '        ' + log(8),
             '    return r'])
    if mode == 'inherit':
        # The error is reported for A and for B.
        contract = [line + '||' + line[4:-1] + ',LB)' if line == WRONG else line
                    for line in contract]
        return '\n'.join(ind([f'def {name}(self, c: Cell, b: bool) -> Optional[int]:'] +
                             ind(requires + contract + body)))
    return '\n'.join([f'def {name}(c: Cell, b: bool) -> Optional[int]:'] +
                     ind(requires + contract + body))


def run(source, name):
    """Runs the function in CPython: its outcome and c.val each time a loop condition is reached."""
    states = {}

    def LOG(loop, values, val):
        seen = states.setdefault(loop, {})
        assert values not in seen, (name, loop, values)
        seen[values] = val

    ns = {'LOG': LOG}
    stub = types.ModuleType('nagini_contracts.contracts')
    for n in ['Requires', 'Ensures', 'Exsures', 'Acc', 'Invariant', 'Result']:
        setattr(stub, n, lambda *a, **k: True)
    stub.Old = lambda x: x
    stub.__all__ = [n for n in dir(stub) if not n.startswith('_')]
    sys.modules['nagini_contracts'] = types.ModuleType('nagini_contracts')
    sys.modules['nagini_contracts.contracts'] = stub
    with warnings.catch_warnings():
        warnings.simplefilter('ignore')
        exec(compile(HEADER + '\n\n' + source, '<generated>', 'exec'), ns)
    c = ns['Cell']()
    try:
        outcome = ('ret', ns[name](c, True), c.val)
    except Exception as e:
        outcome = ('exc', type(e).__name__, c.val)
    return outcome, states


def make(frames, exit, index, mode):
    """Returns the sources of the functions for one nesting."""
    name = f'f{index}_' + '_'.join(frames) + '_' + exit
    lines = build(frames, exit)
    (kind, what, val), states = run(render(name, lines, [], None, 'plain'), name)
    if mode == 'inline':
        val = val * 10 + 8
    if kind == 'ret':
        result = ('Result() is None' if what is None
                  else f'Result() is not None and Result() == {what}')
        right = [f'Ensures(Acc(c.val) and c.val == {val} and {result})']
        # The same with the error as a result of the Viper method.
        variants = [(name, right), (name + '_x', right + ['Exsures(Exception, False)']),
                    (name + '_wrong', [WRONG, f'Ensures(Acc(c.val) and c.val == {val + 1})'])]
    else:
        variants = [(name, ['Ensures(False)', f'Exsures({what}, Acc(c.val) and c.val == {val})']),
                    (name + '_wrong', ['Ensures(False)', WRONG,
                                       f'Exsures({what}, Acc(c.val) and c.val == {val + 1})'])]
    return [render(n, lines, contract, states, mode) for n, contract in variants]


def main():
    default_dir = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                               'functional', 'verification', 'exits')
    parser = argparse.ArgumentParser(
        description='Generates tests for the ways of leaving try, with and loop statements.')
    parser.add_argument('--depth', type=int, default=2, help='maximal nesting depth')
    parser.add_argument('--mode', choices=MODES, default='plain',
                        help='where the nesting is: in the function itself, in an inlined '
                             'function, or in an inherited method')
    parser.add_argument('--per-file', type=int, default=40, help='nestings per file')
    parser.add_argument('--only', nargs='*', default=[],
                        help='nestings to generate, e.g. finr_loop_tfbrk_ret, or +for for '
                             'all with that frame')
    parser.add_argument('--outdir', default=default_dir)
    args = parser.parse_args()

    cases = []
    for n in range(1, args.depth + 1):
        for frames in itertools.product(FRAMES, repeat=n):
            for exit in EXITS:
                if not valid(frames, exit):
                    continue
                if (not args.only or '_'.join(frames + (exit,)) in args.only or
                        any(o[0] == '+' and o[1:] in frames for o in args.only)):
                    cases.append((frames, exit))
    os.makedirs(args.outdir, exist_ok=True)
    files = 0
    for start in range(0, len(cases), args.per_file):
        text = HEADER
        if args.mode == 'inherit':
            text += '\n\nclass A:'
        for i, (frames, exit) in enumerate(cases[start:start + args.per_file], start):
            for source in make(frames, exit, i, args.mode):
                text += ('\n' if args.mode == 'inherit' else '\n\n') + source + '\n'
        if args.mode == 'inherit':
            text += '\n\n#:: Label(LB)\nclass B(A):\n    pass\n'
        path = os.path.join(args.outdir, f'exits_{args.mode}_{files:02d}.py')
        with open(path, 'w') as f:
            f.write(text)
        files += 1
    print(f'{len(cases)} nestings in {files} files')


if __name__ == '__main__':
    main()
